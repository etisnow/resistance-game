// Кусок GLSL, общий для огня и для прогорающего бейджа: обычный value-noise и
// собранный из него fbm. Отдельной текстуры шума он не требует — всё считается
// в шейдере, поэтому пламя не привязано к размеру картинки и не тайлится.
export const noiseGlsl = `
// Хеш нарочно без sin. Классический fract(sin(...) * 43758.5) на разных
// драйверах считается по-разному: при mediump синус большого аргумента теряет
// точность, шум вырождается в кашу или в константу — и пламя пропадает целиком
// (в Firefox работало, в Chrome нет). Здесь только умножения и fract.
float hash(vec2 p) {
	vec3 p3 = fract(vec3(p.x, p.y, p.x) * 0.1031);
	p3 += dot(p3, vec3(p3.y, p3.z, p3.x) + 33.33);
	return fract((p3.x + p3.y) * p3.z);
}

float noise(vec2 p) {
	vec2 i = floor(p);
	vec2 f = fract(p);
	// Сглаживание Эрмита: с линейной интерполяцией на стыках клеток видны рёбра.
	vec2 u = f * f * (3.0 - 2.0 * f);
	return mix(
		mix(hash(i), hash(i + vec2(1.0, 0.0)), u.x),
		mix(hash(i + vec2(0.0, 1.0)), hash(i + vec2(1.0, 1.0)), u.x),
		u.y
	);
}

// Пять октав: меньше — шум слишком гладкий и пламя выглядит нарисованным.
// Множитель 2.03, а не 2.0, чтобы октавы не совпадали клетками друг с другом.
float fbm(vec2 p) {
	float sum = 0.0;
	float amp = 0.5;
	for (int i = 0; i < 5; i++) {
		sum += amp * noise(p);
		p *= 2.03;
		amp *= 0.5;
	}
	return sum;
}
`;
