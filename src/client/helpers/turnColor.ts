/**
 * Цвет часов хода — по кругу, который наматывает их стрелка (см. Reticle).
 *
 * Круг за кругом: свой синий, жёлтый, оранжевый, красный. Считаем кругами, а не
 * секундами, и в этом весь смысл — круг это то, что видно глазом, и каждый
 * следующий обязан отличаться от предыдущего. По секундам цвет пришлось бы
 * привязывать к длине круга на глазок, и стрелка успевала бы намотать пять
 * оборотов, оставаясь всё того же цвета.
 *
 * Красный — последний, дальше цвет не меняется: тревожнее уже не будет, а тон,
 * продолжающий крутиться по кругу, рано или поздно вернулся бы к спокойному
 * синему и сказал бы ровно противоположное тому, что происходит. Набирать
 * дальше есть чему и без цвета — с этого момента растёт свечение (см.
 * glowWidthMax в Reticle).
 *
 * Круг у стрелки — десять секунд, так что красными часы становятся к тридцатой:
 * это и есть отпущенный на решение срок (см. decisionTimeout), дольше стол не
 * ждёт никого.
 */
const lapColors = [
	// Нулевой круг — тот же синий, каким прицел был до всяких часов.
	0x35C8FF,
	// Дальше — жёлтый и красный из палитры стека действий: тревога на столе
	// везде говорится одними цветами.
	0xFFD93D,
	0xFF8C42,
	0xDD6A5D,
];

const finalColor = 0xDD6A5D;

export const turnTimerColor = (laps: number): number => {
	if (laps < 0) return lapColors[0] ?? finalColor;
	return lapColors[Math.floor(laps)] ?? finalColor;
};
