// Личные заметки игрока о соседях по столу. Перебираются по кругу нажатием на
// кружок и видны только тому, кто их поставил (FR-13).
export enum EPlayerMark {
	// «Свой» — веришь, что он в сопротивлении.
	'clear' = 'clear',
	// «Под вопросом» — пока непонятно.
	'question' = 'question',
	// «Подозрительный» — что-то в его голосах не сходится.
	'suspect' = 'suspect',
	// «Шпион» — уверен.
	'spy' = 'spy',
	'none' = 'none',
}
