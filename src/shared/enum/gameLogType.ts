export enum EGameLog {
	gameStarted = 'gameStarted',
}

/**
 * Тип строки игрового лога. Клиент рисует по нему знак и цвет карточки в стеке
 * действий, поэтому типы отвечают на вопрос «что это было», а не «кто написал».
 *
 * Их ровно столько, сколько разных вещей происходит в «Сопротивлении»: набрали
 * команду, проголосовали, отклонили, сходили на дело. От «Нечто» здесь не
 * осталось ничего — там типы были про колоду, панику и карантин.
 */
export enum EGameLogType {
	// Служебное: сид, старт и конец партии, дисконнекты.
	system = 'system',
	// Набор команды: лидер зовёт, берёт, пересобирает состав.
	team = 'team',
	// Голосование за состав и его вскрытие.
	vote = 'vote',
	// Состав отклонён — счётчик отклонений вырос.
	reject = 'reject',
	// Команда ушла на дело.
	mission = 'mission',
	// Миссия выполнена.
	success = 'success',
	// Миссия сорвана.
	fail = 'fail',
	// Всё остальное.
	info = 'info',
}
