export enum EGameLog {
	gameStarted = 'gameStarted',
}

// Тип строки игрового лога. Клиент рисует по нему иконку и цвет строки,
// поэтому типов немного и они группируют события по смыслу, а не по карте.
export enum EGameLogType {
	// Служебное: сид, старт/конец игры, перемешивание колоды, дисконнекты.
	system = 'system',
	// Смена хода.
	turn = 'turn',
	// Взятие карты из колоды.
	deck = 'deck',
	// Игрок разыграл карту события.
	card = 'card',
	// Паника.
	panic = 'panic',
	// Обмен картами между игроками.
	trade = 'trade',
	// Отказ от обмена (страх, нет уж спасибо, мимо) и прочая защита.
	defense = 'defense',
	// Карантин: вход/выход/невозможность действия из-за него.
	quarantine = 'quarantine',
	// Смерть игрока.
	death = 'death',
	// Всё остальное.
	info = 'info',
}
