import {EGamePhase} from 'shared/enum/phase';

/**
 * Всё состояние партии «Сопротивления» — один объект (живёт как `game.round`).
 * Никакой колоды, руки и очереди отложенных эффектов: фаза раунда однозначно
 * определяет, чего сервер ждёт и от кого.
 */
export interface IResistanceState {
	phase: EGamePhase;
	/** Номер текущей миссии, 0..4. */
	missionIndex: number;
	/** Исходы миссий: true — успех, false — провал, null — ещё не сыграна. */
	missionResults: (boolean | null)[];
	leaderId: string;
	/** Отклонений подряд в этом раунде: на MAX_REJECTS партия уходит шпионам. */
	rejectCount: number;
	/** Состав команды, который лидер набирает прямо сейчас. */
	team: string[];
	/** Голоса за состав. Наружу уходят только после вскрытия — см. FR-5. */
	votes: Record<string, boolean>;
	/**
	 * Вскрытые голоса: в «Сопротивлении» они открытые — по ним и играют. Живут
	 * ровно ту паузу, что стол на них смотрит (см. revealPause), и гаснут все
	 * разом, когда ход идёт дальше: это ответ на один заданный вопрос, а не
	 * пометка, которая висит на кружке весь раунд.
	 */
	revealedVotes: Record<string, boolean> | null;
	/** Карты миссии: true — «Успех». Наружу уходит только число провалов (FR-9). */
	missionCards: Record<string, boolean>;
	/**
	 * Сколько провалов вскрыла каждая миссия; null — ещё не сыграна. По всем, а не
	 * только по последней: это счёт партии, стол по нему и спорит, а держать его в
	 * голове или отматывать лог — не игра.
	 */
	missionFails: (number | null)[];
	/**
	 * Кого Убийца взял на прицел, но ещё не выстрелил. Видит это весь стол:
	 * наведённый прицел на кружке — часть развязки, а не тайна.
	 */
	assassinAimId: string | null;
	/**
	 * В кого выстрелил Убийца. Остаётся до последнего кадра стола: партия на этом
	 * и кончается, и последнее, что стол видит, — кого назвали (FR-15).
	 */
	assassinTargetId: string | null;
	/** Партия кончилась, роли открыты всем (FR-10). */
	isRolesRevealed: boolean;
}
